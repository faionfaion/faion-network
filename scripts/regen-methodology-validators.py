# The generic-owner and placeholder words the corpus's own validators use.
# `ast_census` needs this to tell a FORBIDDEN_OWNERS-style vocabulary apart
# from a genuine enum, whatever the constant happens to be called.
_HOUSE_VOCAB = {
    "", "?", "all", "anyone", "as shown", "backlog", "changeme", "client",
    "client team", "data team", "design", "design team", "design-team",
    "engineering", "everyone", "features", "fill_me", "fixme", "n/a", "na",
    "none", "null", "ops", "ops team", "ourselves", "placeholder", "see image",
    "somebody", "someone", "squad", "tbd", "team", "the client", "the group",
    "the squad", "the team", "they", "todo", "unassigned", "us", "we", "wip",
    "xxx",
}


def ast_census(source: str) -> dict[str, int]:
    """Count the constraints an existing validator demonstrably ENFORCES,
    binned into the same categories as schema_census().

    The distinction that matters is guard versus constraint. `if "k" in obj:`
    and `if isinstance(v, str) and ...` are guards — they decide whether a
    check applies, they are not themselves checks. `if "k" not in obj:` and
    `if not isinstance(v, str):` are constraints. Scoring guards inflated the
    old side and refused slugs the generator would have strictly improved.
    """
    cen: dict[str, int] = dict.fromkeys(CATEGORIES, 0)
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return cen

    # A file this generator produced is scored from its inlined SCHEMA, not by
    # heuristics. Every generated file carries the same `_FORMATS` table and
    # the same `re.search` calls in its walker, which the pattern heuristic
    # reads as four constraints no matter what the contract says — so a second
    # run refused every file the first run wrote. Reading the schema back
    # makes the comparison exact and the tool idempotent.
    if GENERATED_MARKER in source:
        for node in tree.body:
            if isinstance(node, ast.Assign) and len(node.targets) == 1 \
                    and isinstance(node.targets[0], ast.Name) \
                    and node.targets[0].id == "SCHEMA":
                try:
                    prior = ast.literal_eval(node.value)
                except (ValueError, SyntaxError, TypeError):
                    break
                if isinstance(prior, dict):
                    return schema_census(prior)
                break
        return cen

    # Module-level constants, so `for k in REQUIRED` can be scored by how many
    # keys REQUIRED actually holds, and an ENUMS mapping by how many fields it
    # constrains.
    seqs: dict[str, list] = {}
    maps: dict[str, dict] = {}
    for node in tree.body:
        if not (isinstance(node, ast.Assign) and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)):
            continue
        name = node.targets[0].id
        try:
            value = ast.literal_eval(node.value)
        except (ValueError, SyntaxError, TypeError):
            continue
        if isinstance(value, (list, tuple, set, frozenset)):
            seqs[name] = list(value)
        elif isinstance(value, dict):
            maps[name] = value

    required_names = {n for n in seqs if "REQUIRED" in n.upper()
                      or "MANDATORY" in n.upper() or n.upper().endswith("_KEYS")}

    def _is_house_rule(name: str, members: list) -> bool:
        """A generic-owner or placeholder vocabulary, not an enum. Name alone
        is unreliable — the corpus spells it FORBIDDEN_OWNERS, PLURAL_OWNERS,
        COLLAPSED_OWNERS and GENERIC — so membership decides."""
        if any(tag in name.upper() for tag in
               ("FORBIDDEN", "PLACEHOLDER", "PLURAL", "GENERIC", "BANNED",
                "COLLAPSED", "ANON")):
            return True
        words = [m.lower() for m in members if isinstance(m, str)]
        if not words:
            return False
        hits = sum(1 for w in words if w in _HOUSE_VOCAB)
        return hits * 2 >= len(words)

    enum_names = {n for n, members in seqs.items()
                  if n not in required_names and not _is_house_rule(n, members)}
    house_names = {n for n in seqs if n not in required_names
                   and n not in enum_names}
    # An ENUMS-style mapping of field -> allowed values is one enum per entry.
    for name, mapping in maps.items():
        if mapping and all(isinstance(v, (list, tuple, set, frozenset))
                           for v in mapping.values()):
            cen["enum"] += len(mapping)

    for node in ast.walk(tree):
        if isinstance(node, ast.Compare):
            has_notin = any(isinstance(op, ast.NotIn) for op in node.ops)
            has_member = any(isinstance(op, (ast.In, ast.NotIn)) for op in node.ops)
            # presence: `"key" not in obj` — `"key" in obj` is a guard.
            if has_notin and isinstance(node.left, ast.Constant) \
                    and isinstance(node.left.value, str):
                cen["required"] += 1
            # enum: membership against a named sequence or an inline literal.
            if has_member and not (isinstance(node.left, ast.Constant)
                                   and isinstance(node.left.value, str)):
                for comp in node.comparators:
                    if isinstance(comp, ast.Name) and comp.id in enum_names:
                        cen["enum"] += 1
                    elif isinstance(comp, (ast.Set, ast.List, ast.Tuple)):
                        # `v in (None, "", [], {})` is the house emptiness
                        # idiom, not an enum. An enum is two or more non-empty
                        # scalars.
                        try:
                            members = list(ast.literal_eval(comp))
                        except (ValueError, SyntaxError, TypeError):
                            continue
                        if any(m in (None, "", [], {}) for m in members):
                            cen["placeholder"] += 1
                        elif len(members) >= 2 and all(
                                isinstance(m, (str, int)) and m != "" for m in members):
                            cen["enum"] += 1
            # the generic-owner / placeholder rule
            for comp in node.comparators:
                if isinstance(comp, ast.Name) and comp.id in house_names:
                    cen["placeholder"] += 1
            # length and numeric bounds
            if any(isinstance(op, (ast.Lt, ast.LtE, ast.Gt, ast.GtE))
                   for op in node.ops):
                operands = [node.left, *node.comparators]
                is_len = any(isinstance(o, ast.Call) and isinstance(o.func, ast.Name)
                             and o.func.id == "len" for o in operands)
                if is_len:
                    cen["size"] += 1
                elif any(isinstance(o, ast.Constant) and isinstance(o.value, (int, float))
                         and not isinstance(o.value, bool) for o in operands):
                    cen["numeric"] += 1

        # presence via a loop over a REQUIRED-ish list
        if isinstance(node, ast.For) and isinstance(node.iter, ast.Name) \
                and node.iter.id in required_names:
            cen["required"] += len(seqs[node.iter.id])

        # `not isinstance(...)` is a type constraint; a bare isinstance is a guard.
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not) \
                and isinstance(node.operand, ast.Call) \
                and isinstance(node.operand.func, ast.Name) \
                and node.operand.func.id == "isinstance":
            cen["type"] += 1

        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
            attr = node.func.attr
            if attr == "compile" and isinstance(node.func.value, ast.Name) \
                    and node.func.value.id == "re":
                cen["pattern"] += 1
            elif attr in ("match", "search", "fullmatch"):
                cen["pattern"] += 1

    # `re.compile` at module level plus its `.match` in validate() is one
    # constraint counted twice.
    cen["pattern"] = (cen["pattern"] + 1) // 2
    # Placeholder rules are a fixed set on the new side; cap the old side the
    # same way so the two are comparable.
    cen["placeholder"] = min(cen["placeholder"], 3)
    return cen


def probe_old(script: Path, fixture: Any, timeout: float = 20.0) -> int | None:
    """Run the on-disk validator against a fixture. 0 accept, 1 reject,
    None if it could not be run meaningfully.

    The corpus is not consistent about how a validator takes its artefact:
    1,959 declare `--file`, 200 take a bare positional path. Probing only
    `--file` made every one of those 200 exit 2, which reads as "inconclusive"
    and silently drops the behavioural half of the safety net. Both forms are
    tried before giving up.
    """
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as fh:
        json.dump(fixture, fh)
        path = fh.name
    try:
        for argv in (["--file", path], [path]):
            try:
                proc = subprocess.run(
                    [sys.executable, str(script), *argv],
                    capture_output=True, text=True, timeout=timeout,
                )
            except (subprocess.TimeoutExpired, OSError):
                return None
            if proc.returncode in (0, 1):
                return proc.returncode
    finally:
        Path(path).unlink(missing_ok=True)
    return None


def alien_probes(ok: Any) -> list[tuple[str, Any]]:
    """Type-preserving substitutions on every top-level field.

    The schema-derived mutations only ever exercise constraints the contract
    declares, so they are blind to the common case: a validator that pins a
    semver, a date or the slug itself while the schema says nothing but
    `"type": "string"`. Swapping in an alien-but-well-typed value surfaces
    exactly those undeclared rules.
    """
    out: list[tuple[str, Any]] = []
    if not isinstance(ok, dict):
        return out
    for key, value in ok.items():
        if isinstance(value, bool):
            alien: Any = not value
        elif isinstance(value, str):
            alien = "zzz-probe-value"
        elif isinstance(value, int):
            alien = 424242
        elif isinstance(value, float):
            alien = 424242.5
        elif isinstance(value, list):
            alien = ["zzz-probe-value"]
        elif isinstance(value, dict):
            continue  # a nested object is covered by its own schema walk
        else:
            continue
        out.append((f"an undeclared rule on {key}", {**ok, key: alien}))
    return out


def behavioural_weaker(script: Path, ok: Any, probes: list,
                       new_validate) -> tuple[bool, list[str]]:
    """Probes the new validator ACCEPTS are the only ones that can expose a
    regression. Sound only when the old validator accepts the base fixture —
    otherwise it rejects every mutation for an unrelated reason, and the
    comparison says nothing.

    Stops at the first loss: one is enough to refuse the slug, and each probe
    costs a subprocess.

    Returns (conclusive, losses). `conclusive` is False when the old validator
    would not accept its own valid artefact — then it rejects every probe for
    an unrelated reason and only the static census is guarding the slug, which
    the report has to say out loud rather than imply.
    """
    if probe_old(script, ok) != 0:
        return False, []
    for description, fixture in probes:
        if new_validate(fixture):
            continue  # new rejects it too — no regression possible
        if probe_old(script, fixture) == 1:
            return True, [description]
    return True, []


