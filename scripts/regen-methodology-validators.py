def _set_path(obj: Any, path: list, value: Any) -> Any:
    """Return a deep copy of obj with path set to value."""
    clone = json.loads(json.dumps(obj))
    cur = clone
    for step in path[:-1]:
        cur = cur[step]
    cur[path[-1]] = value
    return clone


def _del_path(obj: Any, path: list) -> Any:
    clone = json.loads(json.dumps(obj))
    cur = clone
    for step in path[:-1]:
        cur = cur[step]
    del cur[path[-1]]
    return clone


def _resolve(ok: Any, dotted: str) -> tuple[list, Any] | None:
    """Turn a schema path such as `a.b[]` into a concrete key path into OK."""
    keys: list = []
    cur = ok
    for part in dotted.split("."):
        if not part:
            continue
        array_depth = 0
        while part.endswith("[]"):
            part, array_depth = part[:-2], array_depth + 1
        if not isinstance(cur, dict) or part not in cur:
            return None
        keys.append(part)
        cur = cur[part]
        for _ in range(array_depth):
            if not isinstance(cur, list) or not cur:
                return None
            keys.append(0)
            cur = cur[0]
    return keys, cur


# (priority, category, label) — the earlier a mutation appears the more it
# proves; `required` is last because presence is what the weak validators
# already check.
def mutations(schema: dict, ok: Any):
    """Yield (category, description, expect_substring, mutated_fixture)."""
    plans: list[tuple[int, str, str, str, Any]] = []

    for dotted, node in walk_schema(schema):
        if not dotted:
            continue
        resolved = _resolve(ok, dotted)
        if resolved is None:
            continue
        keys, current = resolved

        enum = node.get("enum")
        if enum:
            bad = "__not_in_enum__"
            while bad in enum:
                bad += "x"
            plans.append((0, "enum", f"{dotted} outside its enum",
                          "not in allowed enum", _set_path(ok, keys, bad)))

        if "const" in node:
            fixed = node["const"]
            bad = "__not_the_const__" if not isinstance(fixed, str) else fixed + "-x"
            plans.append((0, "enum", f"{dotted} away from its const",
                          "is not the required const", _set_path(ok, keys, bad)))

        pattern = node.get("pattern")
        if pattern and isinstance(current, str):
            for bad in ("!!!not-a-match!!!", "@@@", "zzzz-9999"):
                if not re.search(pattern, bad):
                    plans.append((1, "pattern", f"{dotted} against its pattern",
                                  "does not match pattern",
                                  _set_path(ok, keys, bad)))
                    break

        fmt = node.get("format")
        if fmt in ("date-time", "date", "email", "uri") and isinstance(current, str):
            plans.append((2, "pattern", f"{dotted} malformed as {fmt}",
                          f"is not a valid {fmt}",
                          _set_path(ok, keys, "not-a-valid-value")))

        if isinstance(current, (int, float)) and not isinstance(current, bool):
            if isinstance(node.get("minimum"), (int, float)):
                plans.append((3, "numeric", f"{dotted} below its minimum",
                              "is below minimum",
                              _set_path(ok, keys, node["minimum"] - 1)))
            if isinstance(node.get("maximum"), (int, float)):
                plans.append((3, "numeric", f"{dotted} above its maximum",
                              "is above maximum",
                              _set_path(ok, keys, node["maximum"] + 1)))

        if isinstance(current, str):
            low = node.get("minLength")
            if isinstance(low, int) and low > 1:
                plans.append((4, "length", f"{dotted} under its minLength",
                              "is under minLength",
                              _set_path(ok, keys, "x" * (low - 1))))
            high = node.get("maxLength")
            if isinstance(high, int):
                plans.append((4, "length", f"{dotted} over its maxLength",
                              "is over maxLength",
                              _set_path(ok, keys, "x" * (high + 1))))

        if isinstance(current, list):
            low = node.get("minItems")
            if isinstance(low, int) and low >= 1:
                plans.append((5, "items", f"{dotted} under its minItems",
                              "is under minItems",
                              _set_path(ok, keys, [])))
            high = node.get("maxItems")
            if isinstance(high, int):
                plans.append((5, "items", f"{dotted} over its maxItems",
                              "is over maxItems",
                              _set_path(ok, keys, [current[0] if current else "x"] * (high + 1))))

        declared = node.get("type")
        if "const" in node:
            declared = None
        if declared == "string" and isinstance(current, str) and not node.get("enum"):
            plans.append((6, "type", f"{dotted} typed as a number",
                          "expected type", _set_path(ok, keys, 12345)))
        elif declared in ("integer", "number") and not node.get("enum"):
            plans.append((6, "type", f"{dotted} typed as a string",
                          "expected type", _set_path(ok, keys, "not-a-number")))
        elif declared == "array":
            plans.append((6, "type", f"{dotted} typed as a string",
                          "expected type", _set_path(ok, keys, "not-a-list")))

    if schema.get("additionalProperties") is False and isinstance(ok, dict):
        plans.append((7, "unknown", "an undeclared top-level field",
                      "unknown field", {**ok, "__undeclared__": "x"}))

    if isinstance(ok, dict) and isinstance(ok.get("owner"), str):
        plans.append((8, "placeholder", "owner set to a generic group",
                      "generic group", {**ok, "owner": "team"}))

    for name in schema.get("required") or []:
        if isinstance(ok, dict) and name in ok and isinstance(ok[name], str):
            plans.append((9, "placeholder", f"{name} left as TBD",
                          "is a placeholder", {**ok, name: "TBD"}))
            break

    for name in schema.get("required") or []:
        if isinstance(ok, dict) and name in ok:
            plans.append((10, "required", f"{name} missing",
                          "missing required field", _del_path(ok, [name])))
            break

    plans.sort(key=lambda p: p[0])
    for _, category, description, expect, fixture in plans:
        yield category, description, expect, fixture


