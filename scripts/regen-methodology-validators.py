#!/usr/bin/env python3
"""regen-methodology-validators.py — rebuild per-methodology output validators
from the JSON Schema their own output contract already declares.

The problem. Every methodology carries `content/02-output-contract.xml` with a
real draft-07 schema inside it, and a `scripts/validate-<slug>.py` that is
supposed to enforce that schema. A large share of those validators check only
that the required keys are present and are not the literal "TBD", while the
contract beside them declares `enum`, `pattern`, `minItems`, `minLength`,
`minimum` and `maximum` that nothing ever reads. Recovering those is
mechanical: the constraints are already written down.

What this does. For each methodology in scope it extracts the schema from the
contract XML and emits a **self-contained** `validate-<slug>.py` that enforces
required / type / enum / pattern / format / minLength / maxLength / minItems /
maxItems / minimum / maximum / additionalProperties, plus the house placeholder
rules (a required field left empty or set to TBD / TODO / FIXME; `owner` set to
a generic group term).

Self-contained is a hard constraint, not a style choice. `faion get-content`
materialises exactly one methodology's `scripts/` into `~/.faion/<slug>/scripts/`
on the end user's machine. A shared helper module would never be shipped
alongside it, so every constraint is inlined into every file. Do not refactor
these toward a common import.

The BAD fixture is derived from the contract by mutating the valid example so
it violates exactly one *declared* constraint, and the generated `--self-test`
asserts the resulting finding names that constraint. A `BAD = {}` fixture only
ever proves the presence checks fire; this proves the file implements the
contract it was generated from.

Safety. The generator can only strengthen. Before replacing a file it measures
the constraints the existing validator enforces, two independent ways:

  1. behavioural — probe the old validator (as a subprocess, its real
     user-visible contract) with the valid fixture and with every mutation the
     NEW validator would accept. If the old one accepts the valid fixture but
     rejects a mutation the new one waves through, the new one is weaker.
  2. static — an AST census of the old source mapped onto the same constraint
     categories the schema declares. If the old file scores higher in any
     single category, the new one is weaker.

A third outcome refuses too: if the old validator will not accept the
contract's own valid example, probe 1 is inconclusive — it rejects every
mutation for an unrelated reason — and "cannot prove not-weaker" is treated as
weaker. Measured on infra/terraform-state, that case hid a cross-field rule no
JSON Schema can express. `--allow-static-only` overrides it deliberately.

Any of these verdicts refuses the slug and leaves the file untouched. Three index
builders were deleted from this repo for silently emptying the files they
targeted; a generator that cannot regress is the price of trusting this one.

Usage:
    regen-methodology-validators.py                     dry-run, whole corpus
    regen-methodology-validators.py --domain dev        dry-run, one domain
    regen-methodology-validators.py --slug a --slug b   dry-run, named slugs
    regen-methodology-validators.py --slug a --write    write those slugs
    regen-methodology-validators.py --self-test         the generator's own tests

Exit codes:
    0 = ran clean            1 = a slug was refused or errored
    2 = usage error
"""
