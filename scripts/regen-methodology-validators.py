_T_SCHEMA = {
    "type": "object",
    "required": ["artefact_id", "owner", "status", "items", "score"],
    "properties": {
        "artefact_id": {"type": "string", "minLength": 3},
        "owner": {"type": "string", "format": "email"},
        "status": {"type": "string", "enum": ["draft", "approved"]},
        "items": {"type": "array", "minItems": 2, "items": {"type": "string"}},
        "score": {"type": "integer", "minimum": 0, "maximum": 10},
        "version": {"type": "string", "pattern": "^\\d+\\.\\d+\\.\\d+$"},
    },
    "additionalProperties": False,
}


def _quiet(fn, *fn_args):
    """Run a generated module's self_test without its output on our streams."""
    import contextlib
    import io

    sink = io.StringIO()
    with contextlib.redirect_stdout(sink), contextlib.redirect_stderr(sink):
        return fn(*fn_args)


def self_test() -> int:
    failures: list[str] = []

    def check(label: str, cond: bool) -> None:
        if not cond:
            failures.append(label)

    ns = exec_module(
        render_validator("t", "T", _T_SCHEMA, {}, {}, "x", "x", "t"), "t")
    validate = ns["validate"]

    good = synth(_T_SCHEMA)
    check(f"synth produces a valid fixture ({validate(good)!r})", not validate(good))

    check("enum violation caught",
          any("not in allowed enum" in e
              for e in validate({**good, "status": "nope"})))
    check("minItems violation caught",
          any("under minItems" in e for e in validate({**good, "items": []})))
    check("minimum violation caught",
          any("below minimum" in e for e in validate({**good, "score": -1})))
    check("maximum violation caught",
          any("above maximum" in e for e in validate({**good, "score": 99})))
    check("minLength violation caught",
          any("under minLength" in e for e in validate({**good, "artefact_id": "ab"})))
    check("pattern violation caught",
          any("does not match pattern" in e
              for e in validate({**good, "version": "not-semver"})))
    check("format violation caught",
          any("is not a valid email" in e for e in validate({**good, "owner": "nope"})))
    check("type violation caught",
          any("expected type" in e for e in validate({**good, "score": "ten"})))
    check("additionalProperties caught",
          any("unknown field" in e for e in validate({**good, "zzz": 1})))
    check("missing required caught",
          any("missing required field" in e
              for e in validate({k: v for k, v in good.items() if k != "owner"})))
    check("generic owner caught",
          any("generic group" in e for e in validate({**good, "owner": "team"})))
    check("placeholder caught",
          any("is a placeholder" in e
              for e in validate({**good, "artefact_id": "TBD"})))
    check("non-object rejected", bool(validate(["not", "an", "object"])))

    # The BAD fixture must violate a *declared* constraint, not merely presence.
    muts = list(mutations(_T_SCHEMA, good))
    check("mutations are generated", bool(muts))
    # Explicitly `bool(muts) and ...` — leaning on `muts and ...` would pass a
    # list where a bool is expected and only work by truthiness accident.
    check("first mutation is not a presence check",
          bool(muts) and muts[0][0] != "required")

    # A generated file must pass its own self-test, and its BAD must be
    # rejected for the stated reason.
    category, violates, expect, bad = muts[0]
    check(f"first mutation is a declared constraint, not a house rule "
          f"({category})", category in ("enum", "pattern", "numeric", "length",
                                        "items", "type", "unknown"))
    src = render_validator("t", "T", _T_SCHEMA, good, bad, expect, violates, "synth")
    gen = exec_module(src, "t2")
    check("generated self-test passes", _quiet(gen["self_test"]) == 0)
    check("generated BAD is not OK", gen["BAD"] != gen["OK"])

    # A self-test that would be circular must fail: swap in a BAD that only
    # trips presence while BAD_EXPECT names the enum rule.
    circular = render_validator("t", "T", _T_SCHEMA, good, {}, expect, violates, "synth")
    circ = exec_module(circular, "t3")
    check("circular fixture is rejected by the harness",
          _quiet(circ["self_test"]) == 1)

    # The regex sampler must produce strings that actually match.
    for pattern in (r"^TASK_[0-9]{3}$", r"^\d+\.\d+\.\d+$", r"^[A-Z]{2,4}-\d+$",
                    r"^(draft|final)$", r"^[a-z0-9-]+$"):
        built = _from_pattern(pattern)
        check(f"sampler builds a match for {pattern} (got {built!r})",
              bool(built) and bool(re.search(pattern, built or "")))

    # Alien probes must cover every top-level field and preserve its type.
    aliens = alien_probes(good)
    check("alien probes cover every top-level field",
          len(aliens) == len([k for k, v in good.items() if not isinstance(v, dict)]))
    for _, fixture in aliens:
        differing = [k for k in good if fixture[k] != good[k]]
        check("an alien probe changes exactly one field", len(differing) == 1)

    # Idempotency: re-censusing a file this generator wrote must reproduce the
    # schema's own census exactly, or a second run refuses everything the
    # first run wrote.
    generated = render_validator("t", "T", _T_SCHEMA, good, bad, expect, violates, "s")
    check(f"generated file re-censuses to its own schema "
          f"({ast_census(generated)} vs {schema_census(_T_SCHEMA)})",
          ast_census(generated) == schema_census(_T_SCHEMA))
    check("a generated file is recognised as generated",
          GENERATED_MARKER in generated)

    # AST census: a presence-only validator must score below the schema.
    weak = (
        "REQUIRED = ['artefact_id', 'owner', 'status', 'items', 'score']\n"
        "def validate(obj):\n"
        "    errs = []\n"
        "    for k in REQUIRED:\n"
        "        if k not in obj:\n"
        "            errs.append(k)\n"
        "    return errs\n"
    )
    weak_cen = ast_census(weak)
    new_cen = schema_census(_T_SCHEMA)
    check(f"weak validator scores no enum ({weak_cen})", weak_cen["enum"] == 0)
    check("schema census beats the weak validator",
          all(new_cen[c] >= weak_cen[c] for c in CATEGORIES))

    # A strong validator the schema cannot match must be refused.
    strong = (
        "import re\n"
        "P1 = re.compile('a')\nP2 = re.compile('b')\nP3 = re.compile('c')\n"
        "P4 = re.compile('d')\nP5 = re.compile('e')\nP6 = re.compile('f')\n"
        "def validate(obj):\n"
        "    return [p for p in (P1, P2, P3, P4, P5, P6) if not p.match(str(obj))]\n"
    )
    strong_cen = ast_census(strong)
    check(f"strong validator out-scores this schema on pattern ({strong_cen})",
          strong_cen["pattern"] > new_cen["pattern"])

    # Contract extraction against the corpus's reference case.
    ref = (KNOWLEDGE / "dev" / "diagram-as-code-mermaid-structurizr"
           / "content" / "02-output-contract.xml")
    if ref.is_file():
        parsed = read_contract(ref)
        check("reference contract yields a schema",
              isinstance(parsed["schema"], dict)
              and "diagrams" in (parsed["schema"].get("properties") or {}))
        check("reference contract yields the valid example",
              isinstance(parsed["example"], dict)
              and parsed["example"].get("owner") == "ruslan@faion.net")

    for f in failures:
        sys.stderr.write(f"self-test FAIL: {f}\n")
    if failures:
        return 1
    sys.stdout.write("self-test OK\n")
    return 0


