def _pyliteral(obj: Any, indent: int = 0) -> str:
    """Deterministic, diff-stable literal. json.dumps then fix the three
    tokens Python spells differently."""
    text = json.dumps(obj, indent=2, ensure_ascii=False, sort_keys=False)
    text = re.sub(r"(?<![\w\"])\btrue\b", "True", text)
    text = re.sub(r"(?<![\w\"])\bfalse\b", "False", text)
    text = re.sub(r"(?<![\w\"])\bnull\b", "None", text)
    if indent:
        pad = " " * indent
        text = "\n".join(pad + line if i else line
                         for i, line in enumerate(text.splitlines()))
    return text


