SUPPORTED = {
    "type", "enum", "pattern", "format", "minLength", "maxLength",
    "minItems", "maxItems", "minimum", "maximum", "exclusiveMinimum",
    "exclusiveMaximum", "required", "properties", "items",
    "additionalProperties",
}
IGNORED_NOISE = {"$schema", "$id", "title", "description", "default",
                 "examples", "$comment", "uniqueItems", "definitions"}


def walk_schema(schema: Any, path: str = ""):
    """Yield (path, node) for every schema node this generator understands."""
    if not isinstance(schema, dict):
        return
    yield path, schema
    for key, sub in (schema.get("properties") or {}).items():
        yield from walk_schema(sub, f"{path}.{key}" if path else key)
    items = schema.get("items")
    if isinstance(items, dict):
        yield from walk_schema(items, f"{path}[]")


def schema_census(schema: dict) -> dict[str, int]:
    cen = dict.fromkeys(CATEGORIES, 0)
    owner_seen = False
    for path, node in walk_schema(schema):
        cen["required"] += len(node.get("required") or [])
        if node.get("type"):
            cen["type"] += 1
        if node.get("enum") or "const" in node:
            cen["enum"] += 1
        if node.get("pattern"):
            cen["pattern"] += 1
        if node.get("format") in ("date-time", "date", "email", "uri", "uri-reference"):
            cen["pattern"] += 1
        cen["size"] += sum(
            1 for k in ("minLength", "maxLength", "minItems", "maxItems")
            if k in node
        )
        cen["numeric"] += sum(
            1 for k in ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum")
            if k in node
        )
        if node.get("additionalProperties") is False:
            cen["unknown"] += 1
        if path.split(".")[-1] == "owner":
            owner_seen = True
    # Placeholder rules are a fixed set — empty-required, TBD-token, generic
    # owner — not one per field. Counting them per field would show a bogus
    # "+9 placeholder" gain on a slug that gained nothing real.
    cen["placeholder"] = (2 if cen["required"] else 0) + (1 if owner_seen else 0)
    return cen


def declared_keywords(schema: dict) -> dict[str, int]:
    """Raw keyword counts, so a report can say `minItems x3` rather than only
    naming the category the keyword was binned into."""
    counts: dict[str, int] = {}
    every = [k for kws in KEYWORDS_BY_CATEGORY.values() for k in kws]
    for _, node in walk_schema(schema):
        for keyword in every:
            if keyword in node and node[keyword] not in (None, ""):
                counts[keyword] = counts.get(keyword, 0) + 1
        if node.get("additionalProperties") is False:
            counts["additionalProperties"] = counts.get("additionalProperties", 0) + 1
    return counts


def unsupported_keywords(schema: dict) -> set[str]:
    found: set[str] = set()
    stack = [schema]
    while stack:
        node = stack.pop()
        if isinstance(node, dict):
            for key, val in node.items():
                if key in ("properties", "definitions", "$defs"):
                    stack.extend(v for v in val.values() if isinstance(v, dict))
                    continue
                if key in ("oneOf", "anyOf", "allOf", "not", "$ref",
                           "patternProperties", "if", "then", "else"):
                    found.add(key)
                if key == "items" and isinstance(val, dict):
                    stack.append(val)
    return found


