# Constraint categories. Both the schema census and the AST census of an
# existing validator are reported in these terms so the two are comparable.
# `length` and `items` are deliberately one bucket. Both sides express a size
# bound as `len(x) <op> n`, and nothing in the source says whether x is a
# string or a list — scoring one comparison in two bins made the old side
# look twice as strict as it was and refused slugs the generator improves.
CATEGORIES = (
    "required",
    "type",
    "enum",
    "pattern",
    "size",
    "numeric",
    "unknown",
    "placeholder",
)

# The raw schema keywords behind each category, for the per-slug report.
KEYWORDS_BY_CATEGORY = {
    "enum": ("enum", "const"),
    "pattern": ("pattern", "format"),
    "size": ("minLength", "maxLength", "minItems", "maxItems"),
    "numeric": ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum"),
}


