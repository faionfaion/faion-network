_PATTERN_CANDIDATES = [
    "1.0.0", "v1.0.0", "2026-01-01", "2026-01-01T00:00:00Z",
    "owner@example.com", "https://example.com/doc", "example",
    "example-value", "EXAMPLE", "ok", "draft", "abc", "a", "1", "0",
    "example_value", "example/value", "Example Value",
]


_CLASS_SAMPLE = {
    "d": "1", "w": "a", "s": " ", "D": "a", "W": "-", "S": "a",
}


def _from_pattern(pattern: str, limit: int = 200) -> str | None:
    """Build one string matching a simple regex.

    Deliberately a subset: literals, escapes, character classes, `.`,
    `{n[,m]}` / `+` / `*` / `?`, groups and top-level alternation (first
    branch wins). Anything else returns None and the caller falls back to its
    candidate list. Contract patterns are things like `^TASK_[0-9]{3}$` and
    `^\\d+\\.\\d+\\.\\d+$`; this covers them without pulling in a solver.
    """
    body = pattern
    if body.startswith("^"):
        body = body[1:]
    if body.endswith("$") and not body.endswith("\\$"):
        body = body[:-1]

    out: list[str] = []
    i = 0
    while i < len(body):
        ch = body[i]
        if len(out) > limit:
            return None

        if ch == "(":
            depth, j = 1, i + 1
            while j < len(body) and depth:
                if body[j] == "\\":
                    j += 2
                    continue
                depth += (body[j] == "(") - (body[j] == ")")
                j += 1
            if depth:
                return None
            inner = body[i + 1:j - 1]
            for prefix in ("?:", "?i:", "?P<"):
                if inner.startswith(prefix):
                    inner = inner[inner.index(">") + 1:] if prefix == "?P<" \
                        else inner[len(prefix):]
                    break
            if inner.startswith("?"):
                return None
            piece = _from_pattern(inner.split("|")[0], limit)
            if piece is None:
                return None
            i = j
        elif ch == "[":
            j = i + 1
            if j < len(body) and body[j] == "^":
                return None
            while j < len(body) and body[j] != "]":
                j += 2 if body[j] == "\\" else 1
            if j >= len(body):
                return None
            cls = body[i + 1:j]
            piece = _sample_class(cls)
            if piece is None:
                return None
            i = j + 1
        elif ch == "\\":
            if i + 1 >= len(body):
                return None
            nxt = body[i + 1]
            piece = _CLASS_SAMPLE.get(nxt, nxt)
            i += 2
        elif ch == ".":
            piece = "a"
            i += 1
        elif ch in "|":
            break  # top-level alternation: the first branch is enough
        elif ch in "*+?{})]":
            return None  # a quantifier with nothing to quantify
        else:
            piece = ch
            i += 1

        # quantifier attached to the piece just built
        count = 1
        if i < len(body):
            q = body[i]
            if q == "?":
                count, i = 1, i + 1
            elif q == "*":
                count, i = 1, i + 1
            elif q == "+":
                count, i = 1, i + 1
            elif q == "{":
                close = body.find("}", i)
                if close == -1:
                    return None
                spec = body[i + 1:close]
                low = spec.split(",")[0].strip() or "1"
                if not low.isdigit():
                    return None
                count, i = max(int(low), 1), close + 1
            if i < len(body) and body[i] == "?":
                i += 1  # non-greedy marker, no effect on a sample
        out.append(piece * count)

    value = "".join(out)
    try:
        if re.search(pattern, value):
            return value
    except re.error:
        return None
    return None


def _sample_class(cls: str) -> str | None:
    """One character satisfying a `[...]` class body."""
    i = 0
    while i < len(cls):
        if cls[i] == "\\" and i + 1 < len(cls):
            return _CLASS_SAMPLE.get(cls[i + 1], cls[i + 1])
        if i + 2 < len(cls) and cls[i + 1] == "-":
            return cls[i]
        if cls[i] != "-":
            return cls[i]
        i += 1
    return None


def _synth_string(node: dict, key: str) -> str | None:
    if "const" in node:
        return node["const"] if isinstance(node["const"], str) else str(node["const"])
    if node.get("enum"):
        first = node["enum"][0]
        return first if isinstance(first, str) else str(first)
    fmt = node.get("format")
    seeds: list[str] = []
    if fmt == "date-time":
        seeds.append("2026-01-01T00:00:00Z")
    elif fmt == "date":
        seeds.append("2026-01-01")
    elif fmt == "email":
        seeds.append("owner@example.com")
    elif fmt in ("uri", "uri-reference"):
        seeds.append("https://example.com/doc")
    if key == "owner":
        seeds.append("owner@example.com")
    seeds.append(f"example-{key}" if key else "example")
    seeds.extend(_PATTERN_CANDIDATES)

    pattern = node.get("pattern")
    low = node.get("minLength")
    high = node.get("maxLength")
    for seed in seeds:
        value = seed
        if isinstance(low, int) and len(value) < low:
            value = (value + "x" * low)[:max(low, len(value))]
        if isinstance(high, int) and len(value) > high:
            value = value[:high]
        if isinstance(low, int) and len(value) < low:
            continue
        if pattern and not re.search(pattern, value):
            continue
        if fmt in ("date-time", "date", "email", "uri", "uri-reference") and seed != seeds[0]:
            continue
        if not value.strip() or value.strip().lower() in {"tbd", "todo", "n/a"}:
            continue
        return value

    # No canned candidate fits: build one from the pattern itself.
    if pattern:
        built = _from_pattern(pattern)
        if built and built.strip():
            if isinstance(low, int) and len(built) < low:
                return None
            if isinstance(high, int) and len(built) > high:
                return None
            return built
    return None


def synth(node: Any, key: str = "") -> Any:
    """Build a value satisfying one schema node, or raise CannotSynth."""
    if not isinstance(node, dict):
        return f"example-{key}" if key else "example"
    if "const" in node:
        return node["const"]
    if node.get("enum"):
        return node["enum"][0]
    declared = node.get("type")
    if isinstance(declared, list):
        declared = next((t for t in declared if t != "null"), declared[0])

    if declared == "object" or (declared is None and node.get("properties")):
        out: dict[str, Any] = {}
        props = node.get("properties") or {}
        for name in node.get("required") or []:
            out[name] = synth(props.get(name, {"type": "string"}), name)
        for name, sub in props.items():
            if name not in out and len(out) < 24:
                out[name] = synth(sub, name)
        if not out:
            out = {"example": "value"}
        return out
    if declared == "array":
        item = node.get("items")
        count = max(1, int(node.get("minItems") or 1))
        count = min(count, int(node.get("maxItems") or count))
        element = synth(item, key) if isinstance(item, dict) else f"item-{key or 'x'}"
        return [element for _ in range(count)]
    if declared == "integer":
        low = node.get("minimum", node.get("exclusiveMinimum", 1))
        value = int(low) + (1 if "exclusiveMinimum" in node else 0)
        high = node.get("maximum")
        if isinstance(high, (int, float)) and value > high:
            value = int(high)
        return value
    if declared == "number":
        low = node.get("minimum", node.get("exclusiveMinimum", 1))
        value = float(low) + (1.0 if "exclusiveMinimum" in node else 0.0)
        high = node.get("maximum")
        if isinstance(high, (int, float)) and value > high:
            value = float(high)
        return value
    if declared == "boolean":
        return True
    if declared == "null":
        return None
    value = _synth_string(node, key)
    if value is None:
        raise CannotSynth(f"cannot build a string satisfying {node!r}")
    return value


class CannotSynth(Exception):
    pass


def build_ok(schema: dict, example: Any, smoke: Any, validate_fn) -> tuple[Any, str]:
    """Pick the OK fixture: the contract's own valid example when it satisfies
    the schema, a repaired version when it nearly does, a synthesised one
    otherwise. Returns (fixture, provenance)."""
    for candidate, origin in ((example, "contract example"),
                              (smoke, "templates/_smoke-test.json")):
        if isinstance(candidate, dict) and not validate_fn(candidate):
            return candidate, origin

    for candidate, origin in ((example, "contract example, repaired"),
                              (smoke, "_smoke-test.json, repaired")):
        if not isinstance(candidate, dict):
            continue
        try:
            repaired = _repair(candidate, schema)
        except CannotSynth:
            continue
        if not validate_fn(repaired):
            return repaired, origin

    fixture = synth(schema)
    if validate_fn(fixture):
        raise CannotSynth(
            f"synthesised fixture still fails its own schema: {validate_fn(fixture)!r}"
        )
    return fixture, "synthesised from schema"


def _repair(obj: dict, schema: dict) -> dict:
    """Fill missing required keys and drop keys the schema forbids."""
    out = dict(obj)
    props = schema.get("properties") or {}
    for name in schema.get("required") or []:
        if name not in out:
            out[name] = synth(props.get(name, {"type": "string"}), name)
    if schema.get("additionalProperties") is False:
        out = {k: v for k, v in out.items() if k in props}
        for name in schema.get("required") or []:
            if name not in out:
                out[name] = synth(props.get(name, {"type": "string"}), name)
    for name, sub in props.items():
        if name in out and isinstance(sub, dict) and sub.get("type") == "object" \
                and isinstance(out[name], dict):
            out[name] = _repair(out[name], sub)
    return out


