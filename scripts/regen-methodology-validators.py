_JSON_COMMENT = re.compile(r"^\s*//.*$", re.MULTILINE)
_TRAILING_COMMA = re.compile(r",(\s*[}\]])")


def _loads_lenient(text: str) -> Any:
    """Parse JSON, tolerating the // comments and trailing commas that a few
    hand-written contracts carry."""
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass
    cleaned = _TRAILING_COMMA.sub(r"\1", _JSON_COMMENT.sub("", text))
    return json.loads(cleaned)


def _parent_map(tree: ET.ElementTree) -> dict[ET.Element, ET.Element]:
    return {child: parent for parent in tree.iter() for child in parent}


def _in_example(el: ET.Element, parents: dict[ET.Element, ET.Element]) -> str | None:
    """Return the `valid` attribute of the enclosing <example>, or None."""
    cur = el
    while cur in parents:
        cur = parents[cur]
        if cur.tag == "example":
            return (cur.get("valid") or "").strip().lower()
    return None


def _section_title(el: ET.Element, parents: dict[ET.Element, ET.Element]) -> str:
    cur = el
    while cur in parents:
        cur = parents[cur]
        if cur.tag == "section":
            return (cur.get("title") or "").lower()
    return ""


def _schema_score(obj: Any) -> int:
    """How much a parsed blob looks like the artefact schema rather than an
    example payload or some incidental JSON."""
    if not isinstance(obj, dict):
        return -1
    score = 0
    if "$schema" in obj:
        score += 4
    if obj.get("type") == "object":
        score += 2
    if isinstance(obj.get("properties"), dict):
        score += 3
    if isinstance(obj.get("required"), list):
        score += 2
    if "$id" in obj:
        score += 1
    return score


def read_contract(contract: Path) -> dict[str, Any]:
    """Extract {schema, example, notes} from a 02-output-contract.xml."""
    out: dict[str, Any] = {"schema": None, "example": None, "notes": []}
    try:
        tree = ET.parse(contract)
    except (ET.ParseError, OSError) as exc:
        out["notes"].append(f"contract unparseable: {exc}")
        return out
    parents = _parent_map(tree)

    best_schema, best_score = None, 0
    examples: list[Any] = []

    for el in tree.iter():
        if el.tag not in ("schema", "code"):
            continue
        lang = (el.get("lang") or "").lower()
        if el.tag == "code" and lang not in ("", "json"):
            continue
        raw = (el.text or "").strip()
        if not raw.startswith(("{", "[")):
            continue
        try:
            blob = _loads_lenient(raw)
        except (json.JSONDecodeError, ValueError):
            continue

        valid_attr = _in_example(el, parents)
        title = _section_title(el, parents)
        if valid_attr == "true" or "valid example" in title:
            if isinstance(blob, dict):
                examples.append(blob)
            continue
        if valid_attr in ("false",) or "invalid example" in title:
            continue

        score = _schema_score(blob)
        if el.tag == "schema":
            score += 3
        if "schema" in title:
            score += 2
        if score > best_score:
            best_schema, best_score = blob, score

    out["schema"] = best_schema
    if examples:
        out["example"] = examples[0]
    return out


def load_smoke_test(meth_dir: Path) -> Any:
    p = meth_dir / "templates" / "_smoke-test.json"
    if not p.is_file():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


