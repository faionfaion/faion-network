class Result:
    __slots__ = ("slug", "domain", "status", "detail", "old_cen", "new_cen",
                 "source", "script")

    def __init__(self, slug, domain, status, detail="", old_cen=None,
                 new_cen=None, source=None, script=None):
        self.slug = slug
        self.domain = domain
        self.status = status
        self.detail = detail
        self.old_cen = old_cen or {}
        self.new_cen = new_cen or {}
        self.source = source
        self.script = script

    def gains(self) -> str:
        bits = []
        for cat in CATEGORIES:
            delta = self.new_cen.get(cat, 0) - self.old_cen.get(cat, 0)
            if delta > 0:
                bits.append(f"+{delta} {cat}")
        return ", ".join(bits) or "no net gain"


def process(meth_dir: Path, deep_probe: bool = True,
            allow_static_only: bool = False) -> Result:
    domain, slug = meth_dir.parent.name, meth_dir.name
    contract = meth_dir / "content" / "02-output-contract.xml"
    script = meth_dir / "scripts" / f"validate-{slug}.py"

    if not contract.is_file():
        return Result(slug, domain, "no-contract")
    parsed = read_contract(contract)
    schema = parsed["schema"]
    if not isinstance(schema, dict) or not (schema.get("properties")
                                            or schema.get("required")):
        return Result(slug, domain, "no-schema",
                      "; ".join(parsed["notes"]) or "no JSON Schema in the contract")
    if not script.is_file():
        return Result(slug, domain, "no-validator",
                      f"missing scripts/validate-{slug}.py")

    exotic = unsupported_keywords(schema)
    new_cen = schema_census(schema)
    old_src = script.read_text(encoding="utf-8", errors="replace")
    old_cen = ast_census(old_src)

    title = (schema.get("title") or slug.replace("-", " ")).strip()

    # A throwaway module to run the checker over candidate fixtures while the
    # fixtures are still being chosen.
    probe_src = render_validator(slug, title, schema, {}, {}, "x", "x", "probe")
    try:
        probe_ns = exec_module(probe_src, slug)
    except Exception as exc:  # noqa: BLE001 — a generated file that will not import
        return Result(slug, domain, "error", f"generated module failed to import: {exc}")
    new_validate = probe_ns["validate"]

    try:
        ok, ok_origin = build_ok(schema, parsed["example"],
                                 load_smoke_test(meth_dir), new_validate)
    except (CannotSynth, RecursionError, TypeError, ValueError) as exc:
        return Result(slug, domain, "no-fixture", str(exc), old_cen, new_cen)

    chosen = None
    probes: list = []
    for category, description, expect, fixture in mutations(schema, ok):
        errs = new_validate(fixture)
        probes.append((description, fixture))
        if chosen is None and errs and any(expect in e for e in errs):
            chosen = (category, description, expect, fixture)
    if chosen is None:
        return Result(slug, domain, "no-mutation",
                      "no declared constraint could be violated distinguishably",
                      old_cen, new_cen)
    probes.extend(alien_probes(ok))

    category, violates, expect, bad = chosen
    source = render_validator(slug, title, schema, ok, bad, expect, violates, ok_origin)

    # The generated file must pass its own self-test before anything else.
    try:
        namespace = exec_module(source, slug)
        if _quiet(namespace["self_test"]) != 0:
            return Result(slug, domain, "error", "generated self-test failed",
                          old_cen, new_cen)
    except Exception as exc:  # noqa: BLE001
        return Result(slug, domain, "error", f"generated self-test raised: {exc}",
                      old_cen, new_cen)

    # --- refuse-to-weaken -------------------------------------------------
    regressions = [f"{cat}: {old_cen[cat]} -> {new_cen[cat]}"
                   for cat in CATEGORIES if old_cen[cat] > new_cen[cat]]
    if regressions:
        return Result(slug, domain, "refused-weaker",
                      "static census regressed — " + "; ".join(regressions),
                      old_cen, new_cen)

    probe_note = "behavioural probe skipped (--no-probe)"
    if deep_probe:
        conclusive, losses = behavioural_weaker(script, ok, probes, new_validate)
        if losses:
            return Result(
                slug, domain, "refused-weaker",
                "existing validator rejects what the new one accepts: "
                + "; ".join(losses[:4]),
                old_cen, new_cen,
            )
        if not conclusive and not allow_static_only:
            # The old validator will not accept its own valid artefact, so
            # every probe comes back rejected for an unrelated reason and the
            # differential proves nothing. "Cannot prove not-weaker" is not
            # "not weaker": measured on infra/terraform-state, the unprovable
            # case hid a real cross-field rule (`rationale` must cite an
            # `inputs_used.name`) that no JSON Schema can express and the
            # generator would have silently dropped.
            return Result(slug, domain, "unprovable",
                          "existing validator rejects the contract's own valid "
                          "example, so it cannot be differentially probed; "
                          "static census alone cannot prove the rewrite is not "
                          "weaker (override with --allow-static-only)",
                          old_cen, new_cen)
        probe_note = ("behavioural probe clean" if conclusive else
                      "STATIC GUARD ONLY, forced with --allow-static-only")

    # Nothing gained is churn: rewriting a file to score the same helps no one
    # and enlarges the diff a reviewer has to read.
    if not any(new_cen[c] > old_cen[c] for c in CATEGORIES):
        return Result(slug, domain, "no-gain",
                      "existing validator already matches the contract's census",
                      old_cen, new_cen)

    declares = declared_keywords(schema)
    detail = (f"OK from {ok_origin}; BAD violates a {category} constraint "
              f"({violates})")
    if declares:
        detail += ("; contract declares "
                   + ", ".join(f"{k} x{v}" for k, v in sorted(declares.items())))
    if exotic:
        detail += f"; unsupported keywords ignored: {sorted(exotic)}"
    detail += f"; {probe_note}"
    return Result(slug, domain, "would-write", detail, old_cen, new_cen,
                  source, script)


