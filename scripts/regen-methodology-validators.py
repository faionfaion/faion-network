def discover(domains: list[str], slugs: list[str]) -> list[Path]:
    out: list[Path] = []
    for meta in sorted(KNOWLEDGE.glob("*/*/meta.json")):
        meth = meta.parent
        if domains and meth.parent.name not in domains:
            continue
        if slugs and meth.name not in slugs:
            continue
        out.append(meth)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    ap.add_argument("--slug", action="append", default=[],
                    help="scope to this methodology slug (repeatable)")
    ap.add_argument("--domain", action="append", default=[],
                    help="scope to this knowledge domain (repeatable)")
    ap.add_argument("--write", action="store_true",
                    help="write the regenerated validators (default: dry-run)")
    ap.add_argument("--dry-run", action="store_true", default=False,
                    help="report only; this is the default")
    ap.add_argument("--allow-static-only", action="store_true",
                    help="write even when the existing validator cannot be "
                         "differentially probed because it rejects its own "
                         "valid example (static census guards it alone)")
    ap.add_argument("--no-probe", action="store_true",
                    help="skip the behavioural probe of the existing validator "
                         "(static census only — faster, weaker)")
    ap.add_argument("--verbose", action="store_true",
                    help="one line per slug, whatever the outcome")
    ap.add_argument("--self-test", action="store_true",
                    help="run the generator's own tests")
    args = ap.parse_args()

    if args.self_test:
        return self_test()
    if args.write and args.dry_run:
        sys.stderr.write("--write and --dry-run contradict each other\n")
        return 2

    targets = discover(args.domain, args.slug)
    if not targets:
        sys.stderr.write("no methodologies matched the given scope\n")
        return 2
    if args.slug:
        missing = {s for s in args.slug} - {t.name for t in targets}
        for slug in sorted(missing):
            sys.stderr.write(f"unknown slug: {slug}\n")
        if missing:
            return 2

    buckets: dict[str, list[Result]] = {}
    for meth in targets:
        result = process(meth, deep_probe=not args.no_probe,
                         allow_static_only=args.allow_static_only)
        buckets.setdefault(result.status, []).append(result)

        if result.status == "would-write":
            # The write path must not be able to fail half way. A Result can
            # only reach `would-write` with both a target and a rendered
            # source, but the write is guarded rather than assumed: a
            # generator whose whole claim is "it can only strengthen" does not
            # get to crash between opening a file and filling it.
            if result.script is None or not result.source:
                result.status = "error"
                result.detail = "no target path or no rendered source"
                buckets.setdefault("error", []).append(result)
                buckets["would-write"].remove(result)
                print(f"ERROR {result.domain}/{result.slug}: {result.detail}")
                continue
            verb = "WRITE" if args.write else "WOULD-WRITE"
            print(f"{verb} {result.domain}/{result.slug}: {result.gains()}")
            print(f"    {result.detail}")
            if args.write:
                target = result.script
                # Render to a sibling temp file and rename: an interrupted run
                # leaves the original validator intact, never a truncated one.
                tmp = target.with_suffix(".py.regen-tmp")
                tmp.write_text(result.source, encoding="utf-8")
                tmp.chmod(0o755)
                tmp.replace(target)
        elif result.status == "refused-weaker":
            print(f"REFUSED {result.domain}/{result.slug}: {result.detail}")
        elif result.status == "unprovable":
            print(f"UNPROVABLE {result.domain}/{result.slug}: {result.detail}")
        elif args.verbose:
            print(f"{result.status.upper()} {result.domain}/{result.slug}: "
                  f"{result.detail}")

    print("\n--- census " + "-" * 52)
    order = ["would-write", "refused-weaker", "unprovable", "no-gain",
             "no-schema", "no-validator", "no-contract", "no-fixture",
             "no-mutation", "error"]
    for status in order + [s for s in buckets if s not in order]:
        if status in buckets:
            print(f"{status:16s} {len(buckets[status]):5d}")
    print(f"{'total':16s} {len(targets):5d}")
    if not args.write and "would-write" in buckets:
        print("\ndry-run: nothing written. Re-run with --write to apply.")

    problems = (len(buckets.get("error", []))
                + len(buckets.get("refused-weaker", []))
                + len(buckets.get("unprovable", [])))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
