README = """\
# tests/browser

Determinism-hardened Playwright harness, generated by `playwright-scaffold.py`.
It captures; it does not judge. The gate is `png-diff.py`.

## What is pinned, and why

| Variable | Pinned to | Left free it gives you |
|---|---|---|
| viewport | %%BPLIST%% x %%HEIGHT%% | a layout that follows the window |
| device scale factor | `1` | 2x pixels on a retina dev machine |
| motion | `reduced` + injected CSS | a screenshot mid-transition |
| clock | `%%CLOCK%%` | a rendered timestamp that never repeats |
| timezone / locale | `UTC` / `en-US` | dates and number formats per machine |
| colour scheme | `light` | a dark-mode runner |
| settle | `networkidle` + fonts + animations + `readyState` | a capture before the web font swaps |
| rasteriser | the CI container image | anti-aliasing per host FreeType |

The last row is the one a config cannot fix. Run the suite in
`%%IMAGE%%`, and bump that image and the Playwright
client pin in the same commit as a baseline re-seed.

## Run

```
%%RUNLOCAL%%
```

Captures land in `actual/`. Seed the baselines by copying the files you have
reviewed into `%%BASELINE%%/` and committing them — an empty baseline
directory makes the CI gate fail loudly rather than pass vacuously.

## The gate

`png-diff.py` (faion `browser` tool pack) compares a baseline against a
capture on two gates at once: changed-pixel ratio, which catches drift, and
largest connected cluster, which catches a small structural shift a ratio
hides. Copy it to `tests/browser/png-diff.py` for the CI step to find it.

## Volatile regions

Mark a live clock or a carousel `data-volatile` and the injected stylesheet
hides it. Reach for `png-diff --ignore` only for a region you cannot mark.
Widening `--max-ratio` to absorb a moving element blinds the whole page.
"""


def parse_breakpoints(spec: str) -> list[int] | str:
    """Comma-separated widths, or one error string."""
    widths: list[int] = []
    for chunk in spec.split(","):
        chunk = chunk.strip()
        if not chunk.isdigit():
            return f"--breakpoints must be comma-separated integers, got {chunk!r}"
        value = int(chunk)
        if not 200 <= value <= 4000:
            return f"breakpoint {value} is outside 200-4000"
        widths.append(value)
    if not widths:
        return "--breakpoints is empty"
    if len(set(widths)) != len(widths):
        return "--breakpoints repeats a width"
    return widths


def parse_flows(text: str) -> list[dict] | str:
    """JSONL of {name, steps, expect}, or one error string. Blank and `#` skipped."""
    flows: list[dict] = []
    seen: set[str] = set()
    for lineno, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        try:
            flow = json.loads(line)
        except json.JSONDecodeError as exc:
            return f"flows line {lineno}: not JSON: {exc}"
        if not isinstance(flow, dict):
            return f"flows line {lineno}: not a JSON object"
        name = str(flow.get("name") or "")
        if not NAME_RE.match(name):
            return f"flows line {lineno}: name {name!r} must match {NAME_RE.pattern}"
        if name in seen:
            return f"flows line {lineno}: duplicate flow name {name!r}"
        seen.add(name)
        steps = flow.get("steps")
        if not isinstance(steps, list) or not steps:
            return f"flows line {lineno}: steps must be a non-empty list"
        for index, step in enumerate(steps, 1):
            if not isinstance(step, dict):
                return f"flows line {lineno} step {index}: not a JSON object"
            action = step.get("action")
            if action not in ACTIONS:
                return (f"flows line {lineno} step {index}: unknown action "
                        f"{action!r}; known: {', '.join(sorted(ACTIONS))}")
            for field in ACTIONS[action]:
                if not str(step.get(field) or ""):
                    return (f"flows line {lineno} step {index}: action {action!r} "
                            f"needs {field!r}")
        flows.append(flow)
    if not flows:
        return "flows file holds no flow"
    return flows


def step_py(step: dict) -> str:
    action = step["action"]
    selector = json.dumps(str(step.get("selector") or ""))
    value = json.dumps(str(step.get("value") or ""))
    if action == "goto":
        return f"    visit(page, {value})"
    if action == "click":
        return f"    page.click({selector})"
    if action == "fill":
        return f"    page.fill({selector}, {value})"
    if action == "press":
        return f"    page.press({selector}, {value})"
    if action == "wait":
        return f"    page.wait_for_selector({selector})"
    return f"    shoot(page, {value})"


def step_ts(step: dict) -> str:
    action = step["action"]
    selector = json.dumps(str(step.get("selector") or ""))
    value = json.dumps(str(step.get("value") or ""))
    if action == "goto":
        return f"  await visit(page, {value});"
    if action == "click":
        return f"  await page.click({selector});"
    if action == "fill":
        return f"  await page.fill({selector}, {value});"
    if action == "press":
        return f"  await page.press({selector}, {value});"
    if action == "wait":
        return f"  await page.waitForSelector({selector});"
    return f"  await shoot(page, {value});"


def helpers_used(flow: dict) -> list[str]:
    """Which harness helpers this flow's steps actually reach. An import the
    spec never uses is a lint failure in the caller's repo on day one."""
    actions = {step["action"] for step in flow["steps"]}
    used = []
    if "screenshot" in actions:
        used.append("shoot")
    if "goto" in actions:
        used.append("visit")
    return used


def render(template: str, mapping: dict[str, str]) -> str:
    """Token substitution. Not str.format: every emitted language is full of
    braces, and escaping them all is how a template acquires a typo."""
    out = template
    for key, value in mapping.items():
        out = out.replace(f"%%{key}%%", value)
    return out


def plan(lang: str, base_url: str, widths: list[int], baseline: str,
         ci: str, flows: list[dict]) -> dict[str, str]:
    """Every file the run would write: relative path -> content. Pure, so two
    runs with the same flags are byte-identical and --self-test can prove it."""
    root = "tests/browser"
    args_json = json.dumps(LAUNCH_ARGS)
    common = {
        "BASE_URL": json.dumps(base_url),
        "BREAKPOINTS": json.dumps(widths),
        "BPLIST": "/".join(str(w) for w in widths),
        "CLOCK": json.dumps(FROZEN_CLOCK),
        "BASELINE": baseline,
        "HEIGHT": str(VIEWPORT_HEIGHT),
        "ARGS": args_json,
        "IMAGE": IMAGE,
    }
    run_local = ("pytest tests/browser -q" if lang == "py"
                 else "npx playwright test -c tests/browser/playwright.config.ts")
    files: dict[str, str] = {
        f"{root}/README.md": render(README, {**common, "RUNLOCAL": run_local}),
        f"{root}/determinism.css": CSS,
        f"{root}/{baseline}/.gitkeep": "",
    }

    if lang == "py":
        files[f"{root}/harness.py"] = render(
            HARNESS_PY, {**common, "BASELINE": json.dumps(baseline)})
        files[f"{root}/conftest.py"] = render(CONFTEST, common)
        files[f"{root}/test_screens.py"] = TEST_SCREENS_PY
        for flow in flows:
            func = flow["name"].replace("-", "_")
            filename = f"test_flow_{func}.py"
            body = [step_py(s) for s in flow["steps"]]
            imports = []
            if flow.get("expect"):
                imports.append("from playwright.sync_api import expect")
                imports.append("")
                body.append("    expect(page.locator("
                            f"{json.dumps(str(flow['expect']))})).to_be_visible()")
            used = helpers_used(flow)
            if used:
                imports.append(f"from harness import {', '.join(used)}")
            files[f"{root}/{filename}"] = render(
                FLOW_PY, {"FILE": filename, "FUNC": func,
                          "IMPORTS": "\n".join(imports).rstrip(),
                          "BODY": "\n".join(body)})
    else:
        files[f"{root}/playwright.config.ts"] = render(CONFIG_TS, common)
        files[f"{root}/determinism.ts"] = render(
            DETERMINISM_TS, {**common, "BASELINE": json.dumps(baseline)})
        files[f"{root}/screens.spec.ts"] = SCREENS_TS
        for flow in flows:
            filename = f"flow-{flow['name']}.spec.ts"
            body = [step_ts(s) for s in flow["steps"]]
            names = ["test"]
            if flow.get("expect"):
                names.append("expect")
                body.append("  await expect(page.locator("
                            f"{json.dumps(str(flow['expect']))})).toBeVisible();")
            imports = [f"import {{ {', '.join(names)} }} from '@playwright/test';"]
            used = helpers_used(flow)
            if used:
                imports.append(
                    f"import {{ {', '.join(used)} }} from './determinism';")
            files[f"{root}/{filename}"] = render(
                FLOW_TS, {"FILE": filename,
                          "TITLE": json.dumps(f"flow {flow['name']}"),
                          "IMPORTS": "\n".join(imports),
                          "BODY": "\n".join(body)})

    if ci == "github":
        files[".github/workflows/browser-visual.yml"] = render(WORKFLOW, {
            **common,
            "SETUP": SETUP_PY if lang == "py" else SETUP_TS,
            "RUN": run_local,
        })
    return files


def self_test() -> list[str]:
    """Prove the generator is deterministic and that the flow parser rejects
    the mistake a caller makes. Writes only into a temporary directory."""
    failures: list[str] = []
    widths = parse_breakpoints("390,768,1440")
    if isinstance(widths, str):
        return [f"OK breakpoints rejected: {widths}"]
    for spec in ("390,x", "12", "390,390", ""):
        if not isinstance(parse_breakpoints(spec), str):
            failures.append(f"breakpoints {spec!r} was accepted")

    flows = parse_flows(OK_FLOWS)
    if isinstance(flows, str):
        return [f"OK flows fixture rejected: {flows}"]
    if len(flows) != 2:
        failures.append(f"OK flows fixture parsed {len(flows)} flows, want 2")
    if not isinstance(parse_flows(BAD_FLOWS), str):
        failures.append("BAD flows fixture produced no finding")

    first = plan("py", "http://localhost:3000", widths, "baseline", "github", flows)
    second = plan("py", "http://localhost:3000", widths, "baseline", "github", flows)
    if first != second:
        failures.append("two runs with identical flags differ")
    if "tests/browser/test_flow_signup.py" not in first:
        failures.append("no spec generated for the signup flow")
    if "page.clock.set_fixed_time" not in first["tests/browser/conftest.py"]:
        failures.append("python config does not freeze the clock")
    if IMAGE not in first[".github/workflows/browser-visual.yml"]:
        failures.append("workflow does not pin the container image")

    # A flow that never screenshots must not import shoot: an unused import is
    # a lint failure in the caller's repo on day one.
    pricing = first.get("tests/browser/test_flow_pricing.py", "")
    if "shoot" in pricing or "visit" not in pricing:
        failures.append("python flow spec imports helpers it does not use")

    typescript = plan("ts", "http://x.test", widths, "baseline", "none", flows)
    if "shoot" in typescript.get("tests/browser/flow-pricing.spec.ts", ""):
        failures.append("ts flow spec imports helpers it does not use")
    config = typescript.get("tests/browser/playwright.config.ts", "")
    for needle in ("deviceScaleFactor: 1", "reducedMotion: 'reduce'",
                   "timezoneId: 'UTC'", "colorScheme: 'light'", "retries: 0"):
        if needle not in config:
            failures.append(f"ts config is missing {needle!r}")
    if any(p.startswith(".github/") for p in typescript):
        failures.append("--ci none still emitted a workflow")

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        for relative, text in first.items():
            target = root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        if not (root / "tests/browser/baseline/.gitkeep").is_file():
            failures.append("baseline/.gitkeep was not written")
        empty = [p for p, t in first.items()
                 if not t.strip() and not p.endswith(".gitkeep")]
        if empty:
            failures.append(f"generated empty files: {empty}")
    return failures


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", help="project root; the harness lands in tests/browser")
    ap.add_argument("--lang", default="py", choices=["py", "ts"],
                    help="pytest-playwright or @playwright/test")
    ap.add_argument("--base-url", default="http://localhost:3000",
                    help="origin the harness navigates against")
    ap.add_argument("--breakpoints", default="390,768,1440",
                    help="comma-separated viewport widths")
    ap.add_argument("--baseline-dir", default="baseline",
                    help="baseline directory, relative to tests/browser")
    ap.add_argument("--ci", default="none", choices=["github", "none"],
                    help="also emit a workflow pinning the Playwright image")
    ap.add_argument("--flows", help="JSONL of {name, steps, expect}, one spec per line")
    ap.add_argument("--force", action="store_true",
                    help="overwrite files that already exist")
    ap.add_argument("--self-test", action="store_true",
                    help="run the built-in fixtures and exit")
    args = ap.parse_args()

    if args.self_test:
        failures = self_test()
        for failure in failures:
            print(f"{NAME}: self-test: {failure}", file=sys.stderr)
        print(f"{NAME}: self-test checks=20 failures={len(failures)}")
        return 1 if failures else 0

    if not args.dir:
        print(f"{NAME}: --dir is required", file=sys.stderr)
        return 2
    project = Path(args.dir)
    if not project.is_dir():
        print(f"{NAME}: --dir is not a directory: {project}", file=sys.stderr)
        return 2

    baseline = args.baseline_dir.strip("/")
    if not baseline or baseline.startswith("/") or ".." in Path(baseline).parts:
        print(f"{NAME}: --baseline-dir must stay under tests/browser",
              file=sys.stderr)
        return 2

    widths = parse_breakpoints(args.breakpoints)
    if isinstance(widths, str):
        print(f"{NAME}: {widths}", file=sys.stderr)
        return 2

    flows: list[dict] = []
    if args.flows:
        try:
            text = Path(args.flows).read_text(encoding="utf-8")
        except OSError as exc:
            print(f"{NAME}: cannot read --flows: {exc}", file=sys.stderr)
            return 2
        parsed = parse_flows(text)
        if isinstance(parsed, str):
            print(f"{NAME}: {parsed}", file=sys.stderr)
            return 2
        flows = parsed

    files = plan(args.lang, args.base_url, widths, baseline, args.ci, flows)
    existing = sorted(p for p in files if (project / p).exists())
    if existing and not args.force:
        print(f"{NAME}: refusing to overwrite {len(existing)} file(s): "
              f"{', '.join(existing[:3])}"
              f"{' …' if len(existing) > 3 else ''} (use --force)",
              file=sys.stderr)
        return 1

    try:
        for relative, text in files.items():
            target = project / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
    except OSError as exc:
        print(f"{NAME}: cannot write into {project}: {exc}", file=sys.stderr)
        return 2

    print(f"{NAME}: lang={args.lang} files={len(files)} "
          f"breakpoints={'/'.join(str(w) for w in widths)} flows={len(flows)} "
          f"ci={args.ci} image={IMAGE} -> {project}/tests/browser")
    return 0


if __name__ == "__main__":
    sys.exit(main())
