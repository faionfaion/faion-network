#!/usr/bin/env python3
"""playwright-scaffold.py — emit a determinism-hardened Playwright harness into
the caller's own repo, where their venv and their CI own the dependency.

Playwright itself cannot ship inside a tool pack: it needs pip plus a ~150 MB
browser download, and a screenshot is non-deterministic across machines by
default — free-running clocks, animations mid-flight, lazy fonts, a device
scale factor inherited from the host display. So this tool never drives a
browser. It writes the config that removes each of those variables: fixed
viewport per breakpoint, deviceScaleFactor 1, reducedMotion reduce, UTC,
en-US, a pinned colorScheme, a frozen clock, `--font-render-hinting=none`,
an injected animation-kill stylesheet, and a navigation that waits for
networkidle and then asserts the page has settled.

The one variable a config cannot pin is font rasterisation, which follows the
host's installed fonts and FreeType build. `--ci github` therefore pins the
`mcr.microsoft.com/playwright:vX.Y.Z-jammy` container image: same rasteriser
on every runner is the only way a baseline PNG survives a runner upgrade.

It is a pure text transform — no network, no browser, byte-identical output
for identical flags.

Input:  --dir the project root (+ optional shape flags)
Output: <project>/tests/browser/**, optionally .github/workflows/browser-visual.yml
        one summary line on stdout.

Exit: 0 written · 1 refused, files exist and --force was not passed · 2 bad
      input (unknown language, malformed breakpoints, unreadable or invalid
      flows file, unwritable destination).
Zero model calls. Zero network calls.
"""
